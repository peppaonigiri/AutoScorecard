def print_strict_split(text: str, width: int = 100):
    """
    严格按字符数分块后打印
    :param text 字符串文本
    :param width 打印时每行固定显示的字符数量
    """
    for i in range(0, len(text), width):
        print(text[i:i + width])


class ArrayCompress(object):
    def __init__(self, allowed_fault: int = 5):
        """
        :param allowed_fault 每255个字节（约318～319个base85编码字符）里允许出现错误的字符数量
        """
        self.__validate_params(allowed_fault)
        self.__n: int = 255
        self.__k: int = self.__n - allowed_fault * 8
        self.__galois_field: Type[GF] = galois.GF(self.__n + 1)
        self.__reed_solomon: ReedSolomon = galois.ReedSolomon(k=self.__k, n=self.__n, field=self.__galois_field)

    def compress(self, array: list) -> str:
        """
        :param array 整数数组
        :return 压缩后的字符串
        """
        sorted_array = sorted(array)
        # 1 生成差分数组
        diffs = [sorted_array[i] - (0 if i == 0 else sorted_array[i - 1]) for i in range(len(sorted_array))]

        # 2 可变长度编码
        byte_stream = bytearray()
        for diff in diffs:
            while diff > 0x7F:
                byte_stream.append((diff & 0x7F) | 0x80)
                diff >>= 7
            byte_stream.append(diff)

        # 3 高性能压缩
        compressed_bytes = zlib.compress(bytes(byte_stream), level=9)

        # 4 reed solomon算法编码
        byte_stream.clear()
        origin_length = len(compressed_bytes)
        for i in range(0, origin_length + 1, self.__k):
            group_bytes: bytes = compressed_bytes[i:min(i + self.__k, origin_length)]
            if len(group_bytes) < self.__k:
                group_bytes = self.__padding(group_bytes, self.__k - len(group_bytes))
            field_data: GF = self.__galois_field(list(group_bytes))
            group_code_bytes: bytes = self.__reed_solomon.encode(field_data).tobytes()
            byte_stream.extend(group_code_bytes)

        return base64.b85encode(bytes(byte_stream)).decode('ascii')

    def decompress(self, compressed_str: str) -> list:
        """
        :param compressed_str 压缩字符串
        :return 解压后的有序整数数组
        """
        if not compressed_str:
            return list()

        # 1 Base85解码
        compressed_encode_bytes = base64.b85decode(compressed_str)

        # 2 reed solomon算法解码
        if len(compressed_encode_bytes) % self.__n != 0:
            raise ValueError("compressed_str is not valid")

        byte_stream = bytearray()
        count = 1
        for i in range(0, len(compressed_encode_bytes), self.__n):
            group_bytes = compressed_encode_bytes[i:i + self.__n]
            field_data: GF = self.__galois_field(list(group_bytes))
            group_decode_bytes, error_text = self.__reed_solomon.decode(field_data, errors=True)
            if error_text == -1:
                raise ValueError(f"Decoding failed in group: {count}")
            byte_stream.extend(group_decode_bytes)
            count += 1

        compressed_bytes = self.__un_padding(bytes(byte_stream))

        # 3 zlib解压
        byte_array = zlib.decompress(compressed_bytes)

        # 4 解析可变长度编码
        diffs = []
        i = 0
        while i < len(byte_array):
            diff = 0
            shift = 0
            # 解析Varint编码[8,10](@ref)
            while True:
                byte = byte_array[i]
                diff |= (byte & 0x7F) << shift
                i += 1
                if not (byte & 0x80):  # 最高位为0时停止
                    break
                shift += 7
            diffs.append(diff)

        # 4 还原差分数组为有序数组[6](@ref)
        sorted_array = [diffs[0]]
        for j in range(1, len(diffs)):
            sorted_array.append(sorted_array[-1] + diffs[j])

        return sorted_array

    @staticmethod
    def __validate_params(allowed_fault: int) -> None:
        if allowed_fault < 0:
            raise ValueError("allowed_fault must be greater than or equal to 0")
        if allowed_fault * 8 >= 128:
            raise ValueError("allowed_fault must be less than 16")

    @staticmethod
    def __padding(byte_array: bytes, padding_length: int) -> bytes:
        return byte_array + bytes([padding_length] * padding_length)

    @staticmethod
    def __un_padding(byte_array: bytes) -> bytes:
        padding_length = byte_array[-1]
        for i in range(len(byte_array) - 1, len(byte_array) - 1 - padding_length, -1):
            if byte_array[i] != padding_length:
                raise ValueError("Invalid data padding")
        return byte_array[:len(byte_array) - padding_length]


